#!/usr/bin/env python3
"""Tier A documentation: a generated activity log and status block built from saved task outcomes.

Accepted in docs/decisions/ADR-0001-automatic-documentation.md. Standard library only; no model, network
or transcript. Entries come from persisted capture receipts, so queued, redelivered and migrated outcomes
reach the docs on the next sync. Only the activity log and the marked block in the current-state page are
written; owner text outside the markers is preserved byte for byte. Docs debt is a local note that code
changed in a turn without a documentation change; it never blocks the agent.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import re
import subprocess
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import memory_capture as mc
import project_memory as pm

LOG, STATE_PAGE = "docs/status/activity-log.md", "docs/status/current-state.md"
SETTINGS, DEBT = ".dreamdocs/documentation.json", ".dreamdocs/docs-state.json"
START, END = "<!-- dreamdocs:recent:start -->", "<!-- dreamdocs:recent:end -->"
SINCE = re.compile(r"<!-- dreamdocs:activity since=(\S+) -->")
LINE = re.compile(r"^- (\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}) UTC · ([a-z_]+)(?: · \[(.+?): ([a-z-]+)\])? · (.*?) <!-- (evt-[0-9a-f]{32}) -->$")
TITLE = re.compile(r"^# Outcome: ([a-z_]+)(?: \((.+), reported ([a-z-]+)\))?$", re.M)
TICK = chr(96)
RECENT, OPEN_TASKS, SUMMARY, DEBT_FILES = 10, 15, 400, 50
NOT_CODE = ("docs/", "memory/", ".dreamdocs/", ".codex/", ".claude/", "human-materials/", ".git/")
BACKFILL = timedelta(days=1)
LOG_HEADER = """---
{"document":"activity-log","status":"generated","owner":"dreamdocs"}
---

# Activity log

Generated by Dreamdocs from saved task outcomes (tier A in the automatic documentation decision).
Each line is one saved outcome as the agent reported it; claims are not independently verified.
Correct the source episode or the topic page, not this log. Newer entries are appended.

<!-- dreamdocs:activity since={since} -->
"""
STATE_HEADER = """---
{"document":"status","status":"draft","owner":"<project-owner>","last_updated":null}
---

# Current State

Owner-maintained status. The marked block below is generated by Dreamdocs from saved outcomes.
"""


def enabled(root):
    """Automatic status docs are on unless .dreamdocs/documentation.json sets automatic_status to false."""
    try:
        value = pm.read_json(pm.confined(root, SETTINGS), {})
    except (OSError, ValueError):
        return True
    return not (isinstance(value, dict) and value.get("automatic_status") is False)


def read_text(path):
    """Exact text: no newline translation, so CRLF owner pages keep their bytes."""
    return path.read_bytes().decode("utf-8").removeprefix("\ufeff") if path.is_file() else None


def one_line(value, limit=SUMMARY):
    value = re.sub(r"\s+", " ", value).strip().replace("](", "] (").replace("<!--", "<!-").replace("-->", "->")
    return value if len(value) <= limit else value[: limit - 1].rstrip() + "…"


def parse_since(value):
    stamp = datetime.fromisoformat(value.replace("Z", "+00:00"))
    return stamp if stamp.tzinfo else stamp.replace(tzinfo=timezone.utc)


def outcome(root, receipt):
    """One log entry from a persisted receipt and its episode, or None when the episode is unreadable."""
    try:
        text = pm.confined(root, receipt["episode"]).read_text(encoding="utf-8").replace("\r\n", "\n")
        meta = pm.metadata(text)
        stamp = parse_since(meta["created_at"]).astimezone(timezone.utc)
    except (OSError, ValueError, KeyError, TypeError):
        return None
    body = re.sub(r"\A---\n.*?\n---\n", "", text, count=1, flags=re.S)
    title = TITLE.search(body)
    status, task, task_status = (title.group(1), title.group(2), title.group(3)) if title else (receipt["outcome"], None, None)
    paragraphs = [p.strip() for p in body[title.end():].split("\n\n") if p.strip()] if title else []
    summary = one_line(paragraphs[0]) if paragraphs else "(no summary)"
    evidence = [s for s in meta.get("source", []) if isinstance(s, str) and s.startswith(("file:", "https://", "id:"))][:3]
    if evidence:
        summary += " Evidence: " + ", ".join(TICK + one_line(s, 200).replace(TICK, "'") + TICK for s in evidence) + "."
    return {"event_id": receipt["event_id"], "at": stamp, "status": status, "task": task, "task_status": task_status, "summary": summary}


def entry_line(item):
    task = f" · [{one_line(item['task'], 120)}: {item['task_status']}]" if item["task"] else ""
    return f"- {item['at']:%Y-%m-%d %H:%M} UTC · {item['status']}{task} · {item['summary']} <!-- {item['event_id']} -->"


def saved_outcomes(root, since, known):
    folder = pm.confined(root, mc.RECEIPTS)
    if not folder.is_dir():
        return []
    floor = (since - BACKFILL).timestamp()  # receipts are written once; older files cannot be newer outcomes
    found = []
    for path in folder.glob("evt-*.json"):
        if path.stem in known or path.stat().st_mtime < floor:
            continue
        try:
            receipt = pm.read_json(path)
            if receipt.get("status") != "persisted" or parse_since(receipt["recorded_at"]) < since:
                continue
        except (OSError, ValueError, KeyError, TypeError, AttributeError):
            continue
        item = outcome(root, receipt)
        if item:
            found.append(item)
    return sorted(found, key=lambda item: (item["at"], item["event_id"]))


def logged(text):
    entries = []
    for line in text.splitlines():
        match = LINE.match(line)
        if match:
            day, clock, status, task, task_status, summary, eid = match.groups()
            entries.append({"day": day, "clock": clock, "status": status, "task": task, "task_status": task_status,
                            "summary": summary, "event_id": eid, "line": line})
    return entries


def block(entries, newline):
    if not entries:
        lines = [START, "## Recent changes (generated)", "", "No saved outcomes yet.", END]
        return newline.join(lines)
    last = entries[-1]
    lines = [START, "## Recent changes (generated)", "",
             f"Built from saved outcomes up to {last['day']} {last['clock']} UTC. Full history: [activity log](activity-log.md).", ""]
    lines += [e["line"] for e in reversed(entries[-RECENT:])]
    latest = {}
    for e in entries:
        if e["task"]:
            latest[e["task"]] = e
    waiting = [e for e in reversed(list(latest.values())) if e["task_status"] != "done"][:OPEN_TASKS]
    if waiting:
        lines += ["", "### Open tasks (latest reported status)", ""]
        lines += [f"- {e['task']}: {e['task_status']} ({e['day']} {e['clock']} UTC) · {one_line(e['summary'], 160)}" for e in waiting]
    lines.append(END)
    return newline.join(lines)


def with_block(text, generated, newline):
    """Replace the marked block, or append it once; refuse a half or reversed marker pair."""
    start, end = text.count(START), text.count(END)
    if start == end == 0:
        return text.rstrip("\r\n") + newline * 2 + generated + newline
    pm.require(start == end == 1 and text.index(START) < text.index(END), "current-state markers are incomplete or duplicated")
    head, rest = text.split(START, 1)
    return head + generated + rest.split(END, 1)[1]


def sync(root, since=None):
    """Append new saved outcomes to the activity log and refresh the status block. Never raises."""
    root = Path(root).resolve()
    if not enabled(root):
        return {"state": "disabled", "added": 0, "findings": []}
    try:
        with mc.writer(root) as free:
            if not free:
                return {"state": "deferred", "added": 0, "findings": ["writer lock busy or Dreamer run active; docs sync retries on the next hook"]}
            log_path, page_path = pm.confined(root, LOG), pm.confined(root, STATE_PAGE)
            log = read_text(log_path)
            if log is None:
                start = since or datetime.now(timezone.utc) - BACKFILL
                log = LOG_HEADER.replace("{since}", start.strftime("%Y-%m-%dT%H:%M:%SZ"))
            marker = SINCE.search(log)
            floor = since or (parse_since(marker.group(1)) if marker else datetime.now(timezone.utc) - BACKFILL)
            newline = "\r\n" if "\r\n" in log else "\n"
            known = {e["event_id"] for e in logged(log)}
            new = [item for item in saved_outcomes(root, floor, known) if item["event_id"] not in known]
            if new:
                last_day = (logged(log) or [{"day": None}])[-1]["day"]
                lines = []
                for item in new:
                    day = f"{item['at']:%Y-%m-%d}"
                    if day != last_day:
                        lines += ["", f"## {day}", ""]
                        last_day = day
                    lines.append(entry_line(item))
                log = log.rstrip("\r\n") + newline + newline.join(lines).replace("\n", newline) + newline
            if new or not log_path.is_file():
                mc.atomic_text(log_path, log)
                pm.require(read_text(log_path) == log, "activity log readback mismatch")
            page = read_text(page_path)
            page_newline = "\r\n" if page and "\r\n" in page else "\n"
            current = page if page is not None else STATE_HEADER.replace("\n", page_newline)
            updated = with_block(current, block(logged(log), page_newline), page_newline)
            if updated != page:
                mc.atomic_text(page_path, updated)
                pm.require(read_text(page_path) == updated, "current-state readback mismatch")
            return {"state": "synced", "added": len(new), "findings": []}
    except (OSError, ValueError) as exc:
        return {"state": "error", "added": 0, "findings": [f"docs sync failed: {exc}"]}


def git(root, *args):
    run = subprocess.run(["git", "-C", str(root), *args], capture_output=True, timeout=10)
    if run.returncode:
        raise OSError("git " + args[0] + " failed")
    return run.stdout.decode("utf-8", "replace")


def changed_files(root, since_head):
    """Files changed by commits since the last observed HEAD plus the current working tree."""
    try:
        head = git(root, "rev-parse", "HEAD").strip()
    except OSError:
        head = None  # a repository without commits yet: only the working tree counts
    names = set()
    if since_head and head and since_head != head:
        try:
            names |= set(git(root, "diff", "--name-only", since_head, head).splitlines())
        except OSError:
            pass  # history rewritten or object missing; fall back to the working tree
    for line in git(root, "status", "--porcelain", "--untracked-files=normal").splitlines():
        path = line[3:].split(" -> ")[-1].strip().strip('"')
        names.add(path)
    return head, {n.replace("\\", "/") for n in names if n}


def classify(names):
    docs = {n for n in names if n.startswith("docs/") and n.endswith(".md") and n not in {LOG, STATE_PAGE}}
    code = {n for n in names if not n.startswith(NOT_CODE) and not n.endswith(".md")}
    return docs, code


def load_debt(root):
    try:
        value = pm.read_json(pm.confined(root, DEBT), {})
    except (OSError, ValueError):
        value = {}
    if not isinstance(value, dict) or value.get("version") != 1:
        value = {"version": 1, "head": None, "files": [], "turns": []}
    return value


def track_debt(root, docs_impact, event_id, task):
    """Record that a turn changed code without touching docs; clear it once docs change. Never raises."""
    root = Path(root).resolve()
    if not enabled(root):
        return None
    try:
        state = load_debt(root)
        head, names = changed_files(root, state.get("head"))
        docs, code = classify(names)
        if docs or docs_impact == "updated":
            state["files"], state["turns"] = [], []
        elif code and docs_impact != "none":
            state["files"] = sorted(set(state["files"]) | code)[:DEBT_FILES]
            state["turns"] = (state["turns"] + [{"event_id": event_id, "task": task, "at": pm.now()}])[-10:]
        state["head"] = head
        ignore = pm.confined(root, ".dreamdocs/.gitignore")
        if not ignore.exists():  # machine-local state; never committed
            mc.atomic_text(ignore, "*\n")
        mc.atomic_text(pm.confined(root, DEBT), json.dumps(state, indent=2, sort_keys=True) + "\n")
        return state
    except (OSError, ValueError, subprocess.SubprocessError):
        return None


def debt_note(root):
    state = load_debt(Path(root).resolve())
    if not state["files"]:
        return None
    sample = ", ".join(state["files"][:5]) + (" and more" if len(state["files"]) > 5 else "")
    return (f"Docs debt: {len(state['files'])} changed code file(s) without a documentation update ({sample}). "
            "Update the matching docs/ topic page in this change, or declare docs_impact \"none\" in the outcome block.")


def stale(root):
    """Health view: what tier A would add now, without writing."""
    root = Path(root).resolve()
    log = read_text(pm.confined(root, LOG))
    page = read_text(pm.confined(root, STATE_PAGE))
    if log is None:
        return {"log": "missing", "pending": None, "block": "missing" if not page or START not in page else "present"}
    marker = SINCE.search(log)
    floor = parse_since(marker.group(1)) if marker else datetime.now(timezone.utc) - BACKFILL
    known = {e["event_id"] for e in logged(log)}
    return {"log": "present", "pending": len(saved_outcomes(root, floor, known)),
            "block": "missing" if not page or START not in page else "present"}

